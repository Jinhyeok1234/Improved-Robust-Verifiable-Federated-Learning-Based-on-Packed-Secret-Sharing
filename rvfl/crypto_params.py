SCHNORR = {"128": SCHNORR_128, "192": SCHNORR_192, "256": SCHNORR_256}


def schnorr_params(level=DEFAULT_LEVEL):
    """Raw {'p', 'q'} for the Z_p* backend."""
    if level not in SCHNORR:
        raise ValueError(f"unknown level {level}; choose from {sorted(SCHNORR)}")
    return dict(SCHNORR[level])


def build_pp(vpss, backend=DEFAULT_BACKEND, level=DEFAULT_LEVEL):
    """Build the public parameters for one backend and level.

    Returns (pp, spec), where spec is a plain dict of ints that pp_from_spec can turn back
    into an identical pp in another process. That matters for the Z_p* backend, whose g and
    h are drawn at random at setup time: every party has to receive the same pair.
    """
    backend = backend.lower()
    if backend == "ec":
        if not getattr(vpss, "HAS_EC", False):
            raise RuntimeError(
                "the VPSS module was built without the elliptic-curve backend; rebuild it "
                "with the OpenSSL headers installed, or pass backend='zp'")
        if level not in CURVES:
            raise ValueError(f"no curve for level {level}; choose from {sorted(CURVES)}")
        d = vpss.ec_setup(CURVES[level])
        spec = dict(backend="ec", level=level, curve=CURVES[level],
                    nid=int(d["nid"]), field_bits=int(d["field_bits"]),
                    p=d["p"].to_int(), q=d["q"].to_int(),
                    g=d["g"].to_int(), h=d["h"].to_int())
    elif backend == "zp":
        raw = schnorr_params(level)
        pp_tmp_p = vpss.BigInt(str(raw["p"]))
        pp_tmp_q = vpss.BigInt(str(raw["q"]))
        g = vpss.find_generator(pp_tmp_p, pp_tmp_q)
        while True:
            h = vpss.find_generator(pp_tmp_p, pp_tmp_q)
            if h.to_int() != g.to_int():
                break
        spec = dict(backend="zp", level=level, curve=None, nid=0, field_bits=0,
                    p=raw["p"], q=raw["q"], g=g.to_int(), h=h.to_int())
    else:
        raise ValueError(f"unknown backend {backend}; choose 'ec' or 'zp'")
    return pp_from_spec(vpss, spec), spec


def pp_from_spec(vpss, spec):
    """Rebuild the public parameters from the dict build_pp returned."""
    pp = vpss.PublicParameters()
    pp.p = vpss.BigInt(str(spec["p"]))
    pp.q = vpss.BigInt(str(spec["q"]))
    pp.g = vpss.BigInt(str(spec["g"]))
    pp.h = vpss.BigInt(str(spec["h"]))
    if spec["backend"] == "ec":
        pp.groupType = vpss.GroupType.EC
        pp.curveNid = int(spec["nid"])
        pp.fieldBits = int(spec["field_bits"])
    else:
        pp.groupType = vpss.GroupType.ZP
    return pp