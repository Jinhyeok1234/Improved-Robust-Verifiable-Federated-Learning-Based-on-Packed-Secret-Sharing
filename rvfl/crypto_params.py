"""Commitment-group parameters for the VPSS.

The protocol needs a cyclic group of prime order q with two generators g and h. Shamir
shares are elements of Z_q, so the dominant communication -- the first-level shares --
depends only on |q|. The group changes the size of a commitment and the cost of one
exponentiation.

  backend="ec"  (default)  a prime-order NIST curve, group element ~2|q| bits
  backend="zp"             a Schnorr group in Z_p*, group element |p| bits.
                           Legacy: it gives the same security level, but its commitments are
                           much larger and its exponentiations much slower than the curve
                           backend, so no experiment uses it. It is kept for reference only.

Security levels follow NIST SP 800-57 equivalent strengths:

  level   curve      |q|    Schnorr (|p|, |q|)
  "128"   P-256      256    (3072, 256)
  "192"   P-384      384    (7680, 384)
  "256"   P-521      521    (15360, 512)

The protocol's own lower bound on q comes from quantisation, not from the group: the
quantisation error norm stays under the verification threshold as long as q > 2^79, so
every level above is far past it.

The Schnorr parameters were generated with gmpy2 (40 Miller-Rabin rounds) and checked in the
VPSS module by a distribute/reconstruct round trip and a Pedersen distribute/verify. For the
curve backend, h is derived by hashing a fixed string to a point, so nobody -- including
whoever generates the parameters -- knows log_g(h).
"""

